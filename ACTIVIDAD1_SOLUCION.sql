CREATE DATABASE ACTIVIDAD1;
USE ACTIVIDAD1;

-- 3. CREACION DE TABLAS Y RELACIONES

CREATE TABLE SUCURSAL
(
  NOMBRE_SUCURSAL VARCHAR(30),
  CIUDAD          VARCHAR(30),
  ACTIVOS         DECIMAL(12,2),
  PRIMARY KEY (NOMBRE_SUCURSAL)
);

DESCRIBE SUCURSAL;


CREATE TABLE EMPLEADO
(
  ID_EMPLEADO         INT AUTO_INCREMENT,
  NOMBRE              VARCHAR(50),
  TELEFONO            VARCHAR(15),
  FECHA_CONTRATACION  DATE,
  ID_JEFE             INT,
  PRIMARY KEY (ID_EMPLEADO),
  FOREIGN KEY (ID_JEFE) REFERENCES EMPLEADO(ID_EMPLEADO)
);

DESCRIBE EMPLEADO;


CREATE TABLE DEPENDIENTE
(
  ID_EMPLEADO       INT,
  NOMBRE_PERSONA_DEP VARCHAR(50),
  PRIMARY KEY (ID_EMPLEADO, NOMBRE_PERSONA_DEP),
  FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO(ID_EMPLEADO)
);

DESCRIBE DEPENDIENTE;


CREATE TABLE CLIENTE
(
  ID_CLIENTE  INT AUTO_INCREMENT,
  NOMBRE      VARCHAR(50),
  CALLE       VARCHAR(50),
  CIUDAD      VARCHAR(30),
  ID_EMPLEADO INT,
  PRIMARY KEY (ID_CLIENTE),
  FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO(ID_EMPLEADO)
);

DESCRIBE CLIENTE;


CREATE TABLE CUENTA
(
  NUM_CUENTA       INT AUTO_INCREMENT,
  SALDO           DECIMAL(10,2),
  NOMBRE_SUCURSAL VARCHAR(30),
  PRIMARY KEY (NUM_CUENTA),
   FOREIGN KEY (NOMBRE_SUCURSAL) REFERENCES SUCURSAL(NOMBRE_SUCURSAL)
);

DESCRIBE CUENTA;


CREATE TABLE CUENTA_AHORRO
(
  NUM_CUENTA    INT,
  TASA_INTERES DECIMAL(4,2),
  PRIMARY KEY (NUM_CUENTA),
  FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA(NUM_CUENTA)
);

DESCRIBE CUENTA_AHORRO;


CREATE TABLE CUENTA_CORRIENTE
(
  NUM_CUENTA   INT,
  DESCUBIERTO DECIMAL(10,2),
  PRIMARY KEY (NUM_CUENTA),
  FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA(NUM_CUENTA)
);

DESCRIBE CUENTA_CORRIENTE;


CREATE TABLE CLI_CUENTA
(
  ID_CLIENTE   INT,
  NUM_CUENTA    INT,
  FECHA_ACCESO DATE
);

DESCRIBE CLI_CUENTA;


ALTER TABLE CLI_CUENTA ADD CONSTRAINT PK_CLI_CUENTA
  PRIMARY KEY (ID_CLIENTE, NUM_CUENTA);

ALTER TABLE CLI_CUENTA ADD CONSTRAINT FK1_CLI_CUENTA
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE);

ALTER TABLE CLI_CUENTA ADD CONSTRAINT FK2_CLI_CUENTA
  FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA(NUM_CUENTA);


DESCRIBE CLI_CUENTA;



CREATE TABLE PRESTAMO
(
  ID_PRESTAMO      INT AUTO_INCREMENT,
  IMPORTE         DECIMAL(10,2),
  NOMBRE_SUCURSAL VARCHAR(30),
  PRIMARY KEY (ID_PRESTAMO),
  FOREIGN KEY (NOMBRE_SUCURSAL) REFERENCES SUCURSAL(NOMBRE_SUCURSAL)
);

DESCRIBE PRESTAMO;


CREATE TABLE CLI_PRESTAMO
(
  ID_CLIENTE INT,
  ID_PRESTAMO INT,
  PRIMARY KEY (ID_CLIENTE, ID_PRESTAMO),
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  FOREIGN KEY (ID_PRESTAMO) REFERENCES PRESTAMO(ID_PRESTAMO)
);

DESCRIBE CLI_PRESTAMO;


CREATE TABLE PAGO
(
  ID_PRESTAMO INT,
  NUM_PAGO    INT,
  FECHA      DATE,
  IMPORTE    DECIMAL(10,2),
  PRIMARY KEY (ID_PRESTAMO, NUM_PAGO),
  FOREIGN KEY (ID_PRESTAMO) REFERENCES PRESTAMO(ID_PRESTAMO)
);

DESCRIBE PAGO;


