-- 5/6. SELECT CON INTERSECCION DE DATOS ENTRE TABLAS

-- clientes con su sucursal de cuenta y saldo
SELECT 
c.NOMBRE AS Cliente, 
cu.NUM_CUENTA, 
cu.SALDO, 
cu.NOMBRE_SUCURSAL

FROM CLIENTE c
INNER JOIN CLI_CUENTA cc 
  ON c.ID_CLIENTE = cc.ID_CLIENTE
INNER JOIN CUENTA cu 
  ON cc.NUM_CUENTA = cu.NUM_CUENTA;

-- clientes que tiene un asesor (empleado) y el jefe del asesor
SELECT 
cl.NOMBRE AS Cliente, 
e.NOMBRE AS Asesor, 
j.NOMBRE AS Jefe_Asesor

FROM CLIENTE cl
LEFT JOIN EMPLEADO e 
  ON cl.ID_EMPLEADO = e.ID_EMPLEADO
LEFT JOIN EMPLEADO j 
  ON e.ID_JEFE = j.ID_EMPLEADO;

-- prestamos con sus titulares y el total pagado hasta ahora
SELECT 
p.ID_PRESTAMO,
p.IMPORTE, 
cl.NOMBRE AS Titular, 
SUM(pg.IMPORTE) AS Total_Pagado

FROM PRESTAMO p
JOIN CLI_PRESTAMO cp 
  ON p.ID_PRESTAMO = cp.ID_PRESTAMO
JOIN CLIENTE cl 
  ON cp.ID_CLIENTE = cl.ID_CLIENTE
JOIN PAGO pg 
  ON p.ID_PRESTAMO = pg.ID_PRESTAMO
GROUP BY p.ID_PRESTAMO, cl.NOMBRE;
